create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  github_url text not null check (github_url like 'https://github.com/%'),
  image_url text not null,
  storage_path text not null,
  owner_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.projects enable row level security;
grant select on public.projects to anon, authenticated;
grant insert, update, delete on public.projects to authenticated;

create policy "Public can view projects" on public.projects
  for select using (true);
create policy "Only portfolio admin can add projects" on public.projects
  for insert to authenticated
  with check (auth.uid() = '862232a0-d679-44d0-95b7-711fd734f0cb'::uuid and owner_id = auth.uid());
create policy "Only portfolio admin can edit projects" on public.projects
  for update to authenticated
  using (auth.uid() = '862232a0-d679-44d0-95b7-711fd734f0cb'::uuid)
  with check (auth.uid() = '862232a0-d679-44d0-95b7-711fd734f0cb'::uuid);
create policy "Only portfolio admin can delete projects" on public.projects
  for delete to authenticated
  using (auth.uid() = '862232a0-d679-44d0-95b7-711fd734f0cb'::uuid);

-- Public image URLs let visitors see project thumbnails. Only admin can upload.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('project-images', 'project-images', true, 3145728, array['image/png','image/jpeg','image/webp'])
on conflict (id) do update set public = true, file_size_limit = 3145728,
  allowed_mime_types = array['image/png','image/jpeg','image/webp'];

create policy "Public can view project images" on storage.objects
  for select using (bucket_id = 'project-images');
create policy "Only portfolio admin can upload project images" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'project-images' and auth.uid() = '862232a0-d679-44d0-95b7-711fd734f0cb'::uuid and (storage.foldername(name))[1] = auth.uid()::text);
create policy "Only portfolio admin can delete project images" on storage.objects
  for delete to authenticated
  using (bucket_id = 'project-images' and auth.uid() = '862232a0-d679-44d0-95b7-711fd734f0cb'::uuid and (storage.foldername(name))[1] = auth.uid()::text);
